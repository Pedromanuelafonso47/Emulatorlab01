// Generates src/mcu/avr/mega-pins.ts from the Arduino AVR core's variant file (pin → port/bit table).
//   node tools/gen-avr-pins.mjs <path-to variants/mega/pins_arduino.h> > src/mcu/avr/mega-pins.ts
import { readFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) { console.error('usage: node tools/gen-avr-pins.mjs <pins_arduino.h>'); process.exit(1); }
const src = readFileSync(file, 'utf8');
const block = src.slice(src.indexOf('digital_pin_to_port_PGM'), src.indexOf('};', src.indexOf('digital_pin_to_port_PGM')));
const re = /\/\/\s*P([A-L])\s+(\d+)\s*\*\*\s*(\d+)\s*\*\*\s*([^\n]*)/g;
const pins = {};
let m;
while ((m = re.exec(block))) {
  const [, port, bit, index, label] = m;
  pins[`D${index}`] = { port, bit: Number(bit) };
  if (/^A\d+$/.test(label.trim())) pins[label.trim()] = { port, bit: Number(bit) };
}
const names = Object.keys(pins).sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)));
if (names.length < 54) { console.error('unexpected table size', names.length); process.exit(1); }
const lines = names.map((n) => `  '${n}': { port: '${pins[n].port}', bit: ${pins[n].bit} },`);
process.stdout.write(`// Generated by tools/gen-avr-pins.mjs from the Arduino AVR core (variants/mega/pins_arduino.h). Do not edit.\n` +
  `export type MegaPort = 'A' | 'B' | 'C' | 'D' | 'E' | 'F' | 'G' | 'H' | 'J' | 'K' | 'L';\n` +
  `export const MEGA_PINS: Record<string, { port: MegaPort; bit: number }> = {\n${lines.join('\n')}\n};\n`);
